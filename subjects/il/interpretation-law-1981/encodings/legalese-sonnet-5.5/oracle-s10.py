#!/usr/bin/env python3
"""A second reading of Law s 10(a) and (b), written in Python from the statute's words, and a generator
for tests-sweep.l4.

Not part of check.sh: run it to regenerate tests-sweep.l4.
  (a) a period of N days from D: the day D is not counted, so the last day is D + N days.
  (b) a period of N months (12N for years) after an event on D ends in the last month, on the day whose number
      in the month is the number of D, and if that month lacks the day, on the last day of the month.

This is the same reading as the L4 in another language. It is there to catch slips in the L4 (an off-by-one
in the month arithmetic, a wrong leap rule), not to second-guess the reading.
"""
import calendar
import datetime as dt
import sys


def last_day_a(d, n):
    return d + dt.timedelta(days=n)


def last_day_b(d, n_months):
    index = d.year * 12 + (d.month - 1) + n_months
    year, month0 = divmod(index, 12)
    month = month0 + 1
    days_in_month = calendar.monthrange(year, month)[1]
    return dt.date(year, month, min(d.day, days_in_month))


def last_day_b_by_analogy_with_a(d, n_months, clamp_ends_on_last_day=False):
    """NOT the reading taken. Fork F1 (R2) of NOTES.md: carry (a)'s exclusion of the start day over to months and
    years and count whole months from the day after: the period begins on D+1 and ends the day before the
    n-month anniversary of D+1. Two conventions for an anniversary that does not exist:
      clamp_ends_on_last_day=False  the anniversary is the last day of its month, and the period ends the day before it;
      clamp_ends_on_last_day=True   the period ends on that last day of the month itself."""
    first = d + dt.timedelta(days=1)
    index = first.year * 12 + (first.month - 1) + n_months
    year, month0 = divmod(index, 12)
    days_in_month = calendar.monthrange(year, month0 + 1)[1]
    anniversary_exists = first.day <= days_in_month
    anniversary = last_day_b(first, n_months)
    if clamp_ends_on_last_day and not anniversary_exists:
        return anniversary
    return anniversary - dt.timedelta(days=1)


def fork1_report():
    """How often (b) and the analogy with (a) give different dates, over every start day in 2024-2025."""
    total = 0
    differ = {False: 0, True: 0}
    last_of_month = {False: 0, True: 0}
    day = dt.date(2024, 1, 1)
    while day <= dt.date(2025, 12, 31):
        for n in (1, 2, 6, 12, 24):
            total += 1
            b = last_day_b(day, n)
            for conv in (False, True):
                if last_day_b_by_analogy_with_a(day, n, conv) != b:
                    differ[conv] += 1
                    if (day + dt.timedelta(days=1)).day == 1:
                        last_of_month[conv] += 1
        day += dt.timedelta(days=1)
    for conv in (False, True):
        name = "period ends on the clamped month-end itself" if conv else "period ends the day before the clamped anniversary"
        print(f"R2, {name}: differs from (b) in {differ[conv]} of {total} cases ({last_of_month[conv]} where the event is on the last day of a month)")
    for case in ((dt.date(2025, 7, 16), 36), (dt.date(2025, 1, 15), 60), (dt.date(2025, 9, 1), 60), (dt.date(2024, 2, 28), 24), (dt.date(2024, 2, 29), 12), (dt.date(2025, 1, 31), 1), (dt.date(2025, 2, 28), 1)):
        print("  ", case[0], f"+{case[1]} months: (b) {last_day_b(*case)}  R2 {last_day_b_by_analogy_with_a(*case)}  R2 other convention {last_day_b_by_analogy_with_a(*case, True)}")


def ymd(d):
    return f"YMD {d.year} {d.month} {d.day}"


def main(out):
    lines = []
    emit = lines.append
    emit("@lang en")
    emit("IMPORT prelude")
    emit("IMPORT daydate")
    emit("IMPORT `il-interpretation-time`")
    emit("")
    emit("-- GENERATED by oracle-s10.py from a second reading of Law s 10(b) in Python. Do not edit by hand.")
    emit("-- Each case asserts two things: the statute's rule as encoded in il-interpretation-time.l4, and that")
    emit("-- daydate's `add months` / `add years` agrees with it. A failure of the second kind would be a finding")
    emit("-- about the library, not about the encoding: the statute governs.")
    emit("")
    emit("§ `Sweep: s 10(b) over month-end and leap-day starts`")
    emit("")
    emit("§§ `Months`")
    emit("")
    n_cases = 0
    for year in (2024, 2025):
        for month in range(1, 13):
            for day in (29, 30, 31):
                if day > calendar.monthrange(year, month)[1]:
                    continue
                start = dt.date(year, month, day)
                for n in (1, 12):
                    end = last_day_b(start, n)
                    emit(f"#ASSERT (`s 10(b) — the last day of a period of` {n} `months after an event on` ({ymd(start)})) EQUALS {ymd(end)}")
                    emit(f"#ASSERT (`add months` ({ymd(start)}) {n}) EQUALS {ymd(end)}")
                    n_cases += 1
    emit("")
    emit("§§ `Years`")
    emit("")
    for start in (dt.date(2024, 2, 29), dt.date(2023, 2, 28), dt.date(2024, 2, 28), dt.date(2025, 3, 1), dt.date(2024, 12, 31)):
        for n in (1, 2, 3, 4, 5):
            end = last_day_b(start, 12 * n)
            emit(f"#ASSERT (`s 10(b) — the last day of a period of` {n} `years after an event on` ({ymd(start)})) EQUALS {ymd(end)}")
            emit(f"#ASSERT (`add years` ({ymd(start)}) {n}) EQUALS {ymd(end)}")
            n_cases += 1
    emit("")
    emit("§§ `Days`")
    emit("")
    for start in (dt.date(2024, 2, 27), dt.date(2025, 2, 27), dt.date(2025, 12, 20), dt.date(2024, 12, 31)):
        for n in (1, 2, 3, 30, 31, 365, 366):
            end = last_day_a(start, n)
            emit(f"#ASSERT (`s 10(a) — the last day of a period of` {n} `days from` ({ymd(start)})) EQUALS {ymd(end)}")
            n_cases += 1
    open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"wrote {out}: {n_cases} cases, {sum(1 for l in lines if l.startswith('#ASSERT'))} assertions")


if __name__ == "__main__":
    if "--fork1" in sys.argv:
        fork1_report()
    else:
        main(sys.argv[1] if len(sys.argv) > 1 else "tests-sweep.l4")
