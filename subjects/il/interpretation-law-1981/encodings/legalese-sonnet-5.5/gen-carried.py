#!/usr/bin/env python3
"""Generate il-interpretation-carried-text.l4: the sections and definitions that are quoted but not computed.

Every quote line and every string comes from the wikitext through quote-hebrew.py, never from memory.
Run: python3 -I gen-carried.py il-interpretation-carried-text.l4
check.sh then runs srcrefs.py over the result, which compares each quote line with the source.
"""
import importlib.util, os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("quote_hebrew", os.path.join(here, "quote-hebrew.py"))
qh = importlib.util.module_from_spec(spec)
spec.loader.exec_module(qh)

LINES = {}
for which in ("law", "ordinance"):
    LINES[which] = open(os.path.join(qh.INPUTS, which + ".wiki"), encoding="utf-8", newline="").read().split("\n")


def seg_lines(which, n):
    return qh.segments(qh.unicodedata.normalize("NFC", LINES[which][n - 1]))


def quote_lines(which, ns):
    tag = "" if which == "law" else "ordinance:"
    out = []
    for n in ns:
        for s in seg_lines(which, n):
            out.append(f"-- src:{tag}{n} | {s}")
    return out


def text_of(which, ns):
    return " ".join(s for n in ns for s in seg_lines(which, n))


def literal(s):
    assert "\\" not in s, s
    return '"' + s.replace('"', '\\"') + '"'


def definition_units(which, first, last, skip):
    """Group lines first..last into units: a unit starts at a line marked as a definition."""
    starts = [n for n in range(first, last + 1) if "סוג=הגדרה" in LINES[which][n - 1]]
    units = []
    for k, n in enumerate(starts):
        end = (starts[k + 1] - 1) if k + 1 < len(starts) else last
        units.append(list(range(n, end + 1)))
    return [u for u in units if u[0] not in skip]


out = []
emit = out.append
emit("@lang en")
emit("")
emit("-- Israel: the provisions of the Interpretation Law 5741-1981 and the Interpretation Ordinance [New Version] that")
emit("-- are CARRIED as quoted text and not computed. GENERATED by gen-carried.py from ../../source; do not edit by hand.")
emit("--")
emit("-- Each unit is the quoted lines (comments, checked by srcrefs.py against the source), an @ref with the same")
emit("-- locators, and a string constant holding the same text. Nothing reads these constants. The reason each is")
emit("-- not computed is in the coverage table of NOTES.md. The text is an unofficial Wikisource consolidation.")
emit("")
emit("§ `Interpretation Law and Ordinance: text carried, not computed`")

count = 0


def unit(which, cite, name, ns):
    global count
    out.append("")
    out.extend(quote_lines(which, ns))
    tag = "" if which == "law" else "ordinance:"
    lo, hi = ns[0], ns[-1]
    loc = f"src:{tag}{lo}" if lo == hi else f"src:{tag}{lo}-{hi}"
    emit(f"@ref {cite} ({loc})")
    emit(f"`{name}` MEANS")
    emit(f"    {literal(text_of(which, ns))}")
    count += 1


def heading(t):
    emit("")
    emit(f"§§ `{t}`")


heading("Law ss 2 to 7, 9: canons of construction")
unit("law", "Interpretation Law s 2", "Law s 2 (carried text, not computed)", [25])
unit("law", "Interpretation Law s 4", "Law s 4 (carried text, not computed)", [65])
unit("law", "Interpretation Law s 5", "Law s 5 (carried text, not computed)", [68])
unit("law", "Interpretation Law s 6", "Law s 6 (carried text, not computed)", [71])
unit("law", "Interpretation Law s 7", "Law s 7 (carried text, not computed)", [74])
unit("law", "Interpretation Law s 9", "Law s 9 (carried text, not computed)", [80])

heading("Law s 3: the definitions this encoding does not compute")
unit("law", "Interpretation Law s 3, opening words", "Law s 3 opening words (carried text, not computed)", [30])
defs = definition_units("law", 31, 62, skip={43, 57, 58})
for k, ns in enumerate(defs, 1):
    unit("law", f"Interpretation Law s 3, definition {k} of {len(defs)} carried", f"Law s 3 carried definition {k} (carried text, not computed)", ns)

heading("Law ss 11 to 19: the scope of a grant of power, and time where none is fixed")
unit("law", "Interpretation Law s 11", "Law s 11 (carried text, not computed)", [90])
unit("law", "Interpretation Law s 12", "Law s 12 (carried text, not computed)", [93])
unit("law", "Interpretation Law s 13", "Law s 13 (carried text, not computed)", [96, 97])
unit("law", "Interpretation Law s 14", "Law s 14 (carried text, not computed)", [100])
unit("law", "Interpretation Law s 15", "Law s 15 (carried text, not computed)", [103])
unit("law", "Interpretation Law s 16", "Law s 16 (carried text, not computed)", [106])
unit("law", "Interpretation Law s 17", "Law s 17 (carried text, not computed)", [109, 110])
unit("law", "Interpretation Law s 18", "Law s 18 (carried text, not computed)", [113])
unit("law", "Interpretation Law s 19", "Law s 19 (carried text, not computed)", [116])

heading("Law ss 22, 25: limbs and sections not computed")
unit("law", "Interpretation Law s 22, limb (1)", "Law s 22 limb (1) (carried text, not computed)", [127, 128])
unit("law", "Interpretation Law s 22, limb (3)", "Law s 22 limb (3) (carried text, not computed)", [127, 130])
unit("law", "Interpretation Law s 25", "Law s 25 (carried text, not computed)", [139])

heading("Law ss 27 to 30: blank in the text, with a note that the text was incorporated elsewhere")
unit("law", "Interpretation Law s 27", "Law s 27 note (carried text, not computed)", [147])
unit("law", "Interpretation Law s 28", "Law s 28 note (carried text, not computed)", [150])
unit("law", "Interpretation Law s 29", "Law s 29 note (carried text, not computed)", [153])
unit("law", "Interpretation Law s 30", "Law s 30 note (carried text, not computed)", [156])

heading("Ordinance: the notes at the top, and s 16's struck subsections")
unit("ordinance", "Interpretation Ordinance, editorial note at the head of the text", "Ordinance head note (carried text, not computed)", [12])
unit("ordinance", "Interpretation Ordinance s 16(1), (2), (3), (5)", "Ordinance s 16 struck subsections (carried text, not computed)", [166, 167, 168, 170])

heading("Ordinance s 1: definitions that apply to enactments given before the Law (not computed)")
unit("ordinance", "Interpretation Ordinance s 1, editorial note", "Ordinance s 1 note (carried text, not computed)", [31])
unit("ordinance", "Interpretation Ordinance s 1, opening words", "Ordinance s 1 opening words (carried text, not computed)", [32])
odefs = definition_units("ordinance", 33, 114, skip={107})
for k, ns in enumerate(odefs, 1):
    unit("ordinance", f"Interpretation Ordinance s 1, definition {k} of {len(odefs)} carried", f"Ordinance s 1 carried definition {k} (carried text, not computed)", ns)

# the encoded definitions of "year" and "month" are in the other modules; say so, so the numbering is not a mystery
open(sys.argv[1], "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"wrote {sys.argv[1]}: {count} units ({len(defs)} Law s 3 definitions, {len(odefs)} Ordinance s 1 definitions)")
