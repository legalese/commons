#!/usr/bin/env python3
"""List the branches that rest on one of the two readings 'for a lawyer', and splice the list into NOTES.md.

  python3 -I marginal.py list            print the table
  python3 -I marginal.py write NOTES.md  replace the region between the MARGINAL markers in NOTES.md

Reading (a): a failed "if", a definition read as closed, a closed list, and a flat negative all count as the text's no (JUST FALSE).
Reading (b): a prohibition or grant limited by its own wording is not a no (NOTHING); and a duty derived from an offence is derived, not stated.
A branch on (a) is a FALSE-kind branch whose quoted words are not a "means" definition or an "only" list (or whose comment says `marginal reading (a)` or `read as closed`); a branch on (b) carries `NOTHING-kind (limited by its own wording)` or `marginal reading (b)`.
"""
import glob, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
rows = {}
for path in sorted(glob.glob(os.path.join(HERE, "poca-*.l4"))):
    b = os.path.basename(path)
    if b.startswith(("poca-tests-", "poca-cases-")) or b == "poca-nouns.l4" or b.endswith("-seat.l4"):
        continue
    rule = None; rl = 0
    for i, ln in enumerate(open(path, encoding="utf-8").read().split("\n")):
        m = re.match(r"^`([^`]+)`\s*MEANS", ln)
        if m:
            rule, rl = m.group(1), i + 1
        if rule is None:
            continue
        a = False
        if "FALSE-kind" in ln:
            quote = ln.split("FALSE-kind (the text says no in its own words)", 1)[-1]
            explicit = re.search(r"marginal reading \(a\)|read as closed|read as the text's no|closed definition|closed list", ln)
            # Not contestable: the quoted words are a definition that says "means", or a list closed with "only" / "nothing but".  Everything else (a failed "if", a flat negative) is reading (a).
            plain = re.search(r'\bmeans\b|\bonly\b|nothing but', re.sub(r"\(.*?\)", "", quote.split('"', 1)[-1] if '"' in quote else quote))
            a = bool(explicit) or not plain
        bb = ("marginal reading (b)" in ln) or ("NOTHING-kind (limited by its own wording)" in ln)
        if a or bb:
            d = rows.setdefault((b, rl, rule), [0, 0])
            if a: d[0] += 1
            if bb: d[1] += 1
na = sum(v[0] for v in rows.values()); nb = sum(v[1] for v in rows.values())
out = []
out.append(f"Generated by `python3 -I marginal.py write NOTES.md` from the comments in the layer-1 modules: {len(rows)} rules, {na} branches resting on reading (a) and {nb} on reading (b).")
out.append("")
out.append("- **Reading (a)**, taken: a failed \"if\", a definition (\"means\" or \"is\") read as closed, a list the text closes, and a flat negative all count as the text's no, so the branch answers `JUST FALSE`.")
out.append("  The other reading: \"if A then B\" does not itself say \"if not A then not B\", so the branch would answer `NOTHING` (not covered).")
out.append("- **Reading (b)**, taken: a prohibition or grant limited by its own wording does not say no outside its limit, so the branch answers `NOTHING`.")
out.append("  The other reading: outside its limit the grant is refused (or the prohibition does not bite), so the branch would answer `JUST FALSE`.")
out.append("  The same label covers the duties the text never states but its offence implies (the `MUST` and `SHANT` twins): they are derived from the offence, not stated.")
out.append("")
out.append("| rule | file:line | branches on (a) | branches on (b) |")
out.append("| --- | --- | ---: | ---: |")
for (b, rl, rule), (x, y) in sorted(rows.items()):
    out.append(f"| `{rule}` | {b}:{rl} | {x} | {y} |")
text = "\n".join(out)
if len(sys.argv) > 1 and sys.argv[1] == "write":
    p = sys.argv[2]
    s = open(p, encoding="utf-8").read()
    i = s.index("<!-- MARGINAL:BEGIN -->") + len("<!-- MARGINAL:BEGIN -->")
    j = s.index("<!-- MARGINAL:END -->")
    open(p, "w", encoding="utf-8").write(s[:i] + "\n" + text + "\n" + s[j:])
    print("written:", len(rows), "rules")
else:
    print(text)
