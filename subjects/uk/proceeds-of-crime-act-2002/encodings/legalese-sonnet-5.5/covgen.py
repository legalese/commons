#!/usr/bin/env python3
"""Generate coverage-map.tsv from the rule names in the poca-*.l4 modules, then merge coverage-manual.tsv over it.

A rule whose backticked name starts `s 340(14C) ...` or `sch 9 para 1(1)(a) ...` is the encoding of the row with that label.
The tests column names the test file of the module (poca-X.l4 -> poca-tests-X.l4).
Run:  python3 -I covgen.py        (then:  RAW_DIR=... python3 -I coverage.py check)
"""
import glob, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
rows = {}
for path in sorted(glob.glob(os.path.join(HERE, "poca-*.l4"))):
    base = os.path.basename(path)
    if base.startswith("poca-tests-") or base.startswith("poca-cases-") or base.endswith("-seat.l4") or "-seat-" in base or base == "poca-nouns.l4":
        continue
    tests = "poca-tests-" + base[len("poca-"):]
    for ln in open(path, encoding="utf-8").read().split("\n"):
        m = re.match(r"^`((?:s (\d+[A-Z]*)|sch 9 paras? (\d+[A-Z]*))((?:\([0-9A-Za-z]+\))*)[^`]*)`\s*(MEANS|$)", ln)
        if not m or m.group(5) != "MEANS":
            continue
        full = m.group(1)
        if m.group(2):
            label = f"s {m.group(2)}{m.group(4)}"
        else:
            label = f"sch 9 para {m.group(3)}{m.group(4)}"
        d = rows.setdefault(label, {"rules": [], "tests": set()})
        d["rules"].append(f"`{full}`")
        d["tests"].add(tests)
out = {k: ("encoded", " ; ".join(v["rules"]), ", ".join(sorted(v["tests"]))) for k, v in rows.items()}
man = os.path.join(HERE, "coverage-manual.tsv")
if os.path.exists(man):
    for ln in open(man, encoding="utf-8"):
        if ln.startswith("#") or not ln.strip():
            continue
        f = ln.rstrip("\n").split("\t")
        while len(f) < 4:
            f.append("")
        out[f[0]] = (f[1], f[2], f[3])
with open(os.path.join(HERE, "coverage-map.tsv"), "w", encoding="utf-8") as f:
    f.write("# GENERATED by covgen.py from the rule names in poca-*.l4 and coverage-manual.tsv.  Do not edit; edit the manual file.\n")
    f.write("# label\tdisposition\trules / reason\ttests / fork\n")
    for k in sorted(out):
        f.write(k + "\t" + "\t".join(x.replace("\t", " ") for x in out[k]) + "\n")
print(len(out), "entries")
