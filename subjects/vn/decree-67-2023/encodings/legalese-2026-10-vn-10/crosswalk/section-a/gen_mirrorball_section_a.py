def law(c, p, i, d):
    # Law Dieu 4(24)-(26) (law08:167-177), the oracle's reading.
    return (c and p, i, d)


def round_trip(c, p, i, d):
    if c or p or i:
        return (True, p, True, False)       # the forward map of the merged buyer-or-insured, premium paid as p
    if d:
        return None
    return (False, False, False, False)     # the injured person's empty role


def keeps(c, p, i, d):
    rt = round_trip(c, p, i, d)
    return rt is not None and law(*rt) == law(c, p, i, d)


