#!/usr/bin/env python3
"""Generate sgbau-tests-schedule.l4 from a table of expectations written BY HAND.

The table below was written on 2026-11-03 from the text of the sources (the Notification's cl 1 and its
first-publication line, the Schedule's items, the 2003 edition's operation date in BA1994.txt:4604), BEFORE the
stable row's version table was read.  It is data, not a formula: each cell is stated, so a defect in the rule that
the code applies cannot also be in the expectation.

  python3 -I gen-tests-schedule.py > sgbau-tests-schedule.l4

WHAT THE TABLE SAYS (the reading, in words)
  V1 = the Schedule of three items (broadcast television receiver; broadcast sound receiver; TVRO system).
  V2 = the Schedule of the TVRO system only (S 549/2012).
  Conduct on 31 Dec 2010 is governed by V1 for every reader: S 549/2012 is deemed to operate only from 1 Jan 2011.
  Conduct on or after 1 Jan 2011 is governed by V2 for a reader on or after 31 Oct 2012, and by V1 for a reader
  before that day, who could not have known of the Notification.
  A reader on 31 Oct 2012 itself counts as a reader after publication: the Gazette says 5.00 pm, a DATE has no
  time of day, and the brief for this row says "on or after 31 Oct 2012".  That is a convention, recorded in
  NOTES.md (finding 5), not a reading of the text.
"""

# (label, d, m, y) -- conduct days.  "today" is 3 November 2026, the day the table was written; pinned, not read.
CONDUCT = [
    ("31 Dec 2010", 31, 12, 2010),
    ("1 Jan 2011", 1, 1, 2011),
    ("1 Jun 2011", 1, 6, 2011),
    ("30 Oct 2012", 30, 10, 2012),
    ("31 Oct 2012", 31, 10, 2012),
    ("1 Nov 2012", 1, 11, 2012),
    ("3 Nov 2026 (today)", 3, 11, 2026),
]
# Reading days.
READ = [
    ("1 Aug 2012", 1, 8, 2012),
    ("31 Oct 2012", 31, 10, 2012),
    ("1 Nov 2012", 1, 11, 2012),
    ("3 Nov 2026", 3, 11, 2026),
]

# VERSION[conduct index][reading index], written out cell by cell.  1 = V1 (three items), 2 = V2 (TVRO only).
VERSION = [
    # reader:  1 Aug 2012, 31 Oct 2012, 1 Nov 2012, 3 Nov 2026
    [1, 1, 1, 1],   # conduct 31 Dec 2010
    [1, 2, 2, 2],   # conduct 1 Jan 2011
    [1, 2, 2, 2],   # conduct 1 Jun 2011
    [1, 2, 2, 2],   # conduct 30 Oct 2012
    [1, 2, 2, 2],   # conduct 31 Oct 2012
    [1, 2, 2, 2],   # conduct 1 Nov 2012
    [1, 2, 2, 2],   # conduct 3 Nov 2026 (today); for the 1 Aug 2012 reader this is conduct in the future
]

# What each version says about each apparatus: is it "specified in the First Schedule"?
# V1 lists the television receiver, the sound receiver and the TVRO system; V2 lists the TVRO system only.
SPECIFIED = {
    1: {"tv": True, "radio": True, "tvro": True, "tvdish": True},
    2: {"tv": False, "radio": False, "tvro": True, "tvdish": True},
}
# The Schedule's answer depends on the Schedule facts only.  The s 2(1) first limb (capable of reception) is
# tested in sgbau-tests-act.l4, where an apparatus that is not capable of reception is the control.
KINDS = ["tv", "radio", "tvro", "tvdish"]

NAMES = {
    "tv": "a television set",
    "radio": "a radio set",
    "tvro": "a satellite dish system",
    "tvdish": "a television set with a satellite dish",
}

def d(t):
    _, dd, mm, yy = t
    return f"Date {dd} {mm} {yy}"

out = []
w = out.append
w("""-- GENERATED by gen-tests-schedule.py from a table of expectations written by hand from the sources.
-- Do not edit this file; edit the generator and regenerate.
--
-- FORWARD-LOOKING ROW, TARGET unstable.  Needs the time built-ins.
--
-- Which text of the First Schedule governs conduct on a day, as the law is read on a day:
-- 7 conduct days x 4 reading days, then what each text says about four kinds of apparatus,
-- then the days outside the sources.
--
-- Every assertion pins BOTH axes explicitly, so that no assertion reads the wall clock:
--   EVAL AS OF SYSTEM TIME <reading day>  (EVAL UNDER VALID TIME <conduct day>  <question>)

IMPORT prelude
IMPORT daydate
IMPORT `sgbau-nouns`
IMPORT `sgbau-first-schedule`

TIMEZONE IS "Asia/Singapore"

§ `Four apparatus, described by facts a witness could state`

-- A television set: used for the visual and aural reception of a broadcasting service.
`a television set` MEANS Apparatus WITH
    `capable of or designed or constructed for the reception of a broadcasting service`  IS TRUE
    `used for the aural reception of a broadcasting service`                             IS FALSE
    `used for the visual and aural reception of a broadcasting service`                  IS TRUE
    `capable of direct reception from a satellite in extra-terrestrial space`            IS FALSE

-- A radio set: used for the aural reception of a broadcasting service.
`a radio set` MEANS Apparatus WITH
    `capable of or designed or constructed for the reception of a broadcasting service`  IS TRUE
    `used for the aural reception of a broadcasting service`                             IS TRUE
    `used for the visual and aural reception of a broadcasting service`                  IS FALSE
    `capable of direct reception from a satellite in extra-terrestrial space`            IS FALSE

-- A satellite dish system: capable of direct reception from a satellite.
`a satellite dish system` MEANS Apparatus WITH
    `capable of or designed or constructed for the reception of a broadcasting service`  IS TRUE
    `used for the aural reception of a broadcasting service`                             IS FALSE
    `used for the visual and aural reception of a broadcasting service`                  IS FALSE
    `capable of direct reception from a satellite in extra-terrestrial space`            IS TRUE

-- A television set that has a satellite dish: it fits item 1 and the TVRO item.
`a television set with a satellite dish` MEANS Apparatus WITH
    `capable of or designed or constructed for the reception of a broadcasting service`  IS TRUE
    `used for the aural reception of a broadcasting service`                             IS FALSE
    `used for the visual and aural reception of a broadcasting service`                  IS TRUE
    `capable of direct reception from a satellite in extra-terrestrial space`            IS TRUE

§ `The question, with both axes pinned`

-- Which text governs conduct on `conduct`, as the law is read on `reading`.
GIVEN conduct IS A DATE
      reading IS A DATE
GIVETH A `Version of the First Schedule`
`the text that governs conduct on` MEANS
    `EVAL AS OF SYSTEM TIME` reading
        (`EVAL UNDER VALID TIME` conduct `the version of the First Schedule that governs`)

-- Is the apparatus specified in the Schedule that governs conduct on `conduct`, read on `reading`.
GIVEN apparatus IS AN Apparatus
      conduct IS A DATE
      reading IS A DATE
GIVETH A BOOLEAN
`specified, for conduct on a day, read on a day` MEANS
    `EVAL AS OF SYSTEM TIME` reading
        (`EVAL UNDER VALID TIME` conduct (`apparatus is specified in the First Schedule that governs` apparatus))
""")

vname = {1: "`the First Schedule of three items`", 2: "`the First Schedule of the TVRO system only`"}
count = 0
for ci, c in enumerate(CONDUCT):
    w(f"§ `Conduct on {c[0]}`\n")
    for ri, r in enumerate(READ):
        v = VERSION[ci][ri]
        w(f"-- read on {r[0]}: the text that governs is {'the three-item Schedule' if v == 1 else 'the TVRO-only Schedule'}")
        w(f"#ASSERT `the text that governs conduct on` ({d(c)}) ({d(r)}) EQUALS {vname[v]}")
        count += 1
        for k in KINDS:
            exp = "TRUE" if SPECIFIED[v][k] else "FALSE"
            w(f"#ASSERT `specified, for conduct on a day, read on a day` `{NAMES[k]}` ({d(c)}) ({d(r)}) EQUALS {exp}")
            count += 1
    w("")

w("""§ `Days outside the sources`

-- The first deposited edition operated from 31 July 2003 (BA1994.txt:4602-4604).
-- Conduct before it, or a reader before it, is not covered.  The answer is a refusal, never FALSE.

-- conduct the day before the first deposited edition, read today
#ASSERT REFUSED `the text that governs conduct on` (Date 30 7 2003) (Date 3 11 2026)
#ASSERT REFUSED `specified, for conduct on a day, read on a day` `a television set` (Date 30 7 2003) (Date 3 11 2026)
#ASSERT REFUSED `specified, for conduct on a day, read on a day` `a satellite dish system` (Date 30 7 2003) (Date 3 11 2026)
-- conduct long before it
#ASSERT REFUSED `the text that governs conduct on` (Date 1 10 1994) (Date 3 11 2026)
#ASSERT REFUSED `the text that governs conduct on` (Date 31 12 1994) (Date 1 8 2012)
-- a reader the day before the first deposited edition, asking about conduct in 2011
#ASSERT REFUSED `the text that governs conduct on` (Date 1 6 2011) (Date 30 7 2003)
-- the first covered day, for both: the three-item text
#ASSERT `the text that governs conduct on` (Date 31 7 2003) (Date 31 7 2003) EQUALS `the First Schedule of three items`
#ASSERT `specified, for conduct on a day, read on a day` `a television set` (Date 31 7 2003) (Date 31 7 2003) EQUALS TRUE
#ASSERT `specified, for conduct on a day, read on a day` `a satellite dish system` (Date 31 7 2003) (Date 3 11 2026) EQUALS TRUE
""")
count += 9
w(f"-- assertions generated: {count}")
print("\n".join(out))
