"""Write the fixed-arity layer for 3:2 and its solver obligations.

Usage: python3 -I gen_fixed_arity.py ENCODING_DIR

Writes ENCODING_DIR/tools/kn-majority-fixed.l4.in (render it with render.py like the other templates)
and ENCODING_DIR/prove/kn-fixed-arity.l4.  Both are generated: change this script, not them.

For n owners (n = 2, 3, 5) with pairs p1..pn:
  the largest minority  = the largest sum of some owners' pairs that is no more than half of all,
                          over every choice of owners (2^n of them, the empty choice giving 0);
  the smallest majority = all the pairs less the largest minority (Koppel and Reiss).
Reiss's division (Torah u-Madda Journal 9, 2000, section 6, steps 1-3): a choice of owners that makes up
the largest minority has all its birds below; every other owner but one has all her birds above; the one
left (here, the first owner not chosen) has as many above as makes half of all the birds above.
"""
import itertools
import sys

enc = sys.argv[1]
SIZES = [(2, "two"), (3, "three"), (5, "five")]


def ps(n):
    return [f"p{i}" for i in range(1, n + 1)]


def subsets(n):
    """Every choice of owners but all of them, smallest first, as tuples of 1-based indices."""
    out = []
    for k in range(0, n):
        out.extend(itertools.combinations(range(1, n + 1), k))
    return out


def ssum(sub, names):
    if not sub:
        return "0"
    if len(sub) == 1:
        return names[sub[0] - 1]
    return "(" + " PLUS ".join(names[i - 1] for i in sub) + ")"


def nested_max(terms):
    """A balanced tree of `max`, so its depth is about log2 of the number of terms.  A left-nested chain
    of 31 made main 1.6.108 run past 300 s on the module (2026-11-03); the dev build did not."""
    if len(terms) == 1:
        return terms[0]
    mid = (len(terms) + 1) // 2
    return f"max ({nested_max(terms[:mid])}) ({nested_max(terms[mid:])})"


def given(names):
    w = max(len(x) for x in names)
    lines = [f"GIVEN {names[0].ljust(w)} IS A NUMBER"]
    lines += [f"      {x.ljust(w)} IS A NUMBER" for x in names[1:]]
    return lines


HALF = "`so many pairs, if they are no more than half of all`"


def total(word):
    return f"`all the pairs of {word} nests`"


def lm(word):
    return f"`the largest minority of {word} nests`"


def sm(word):
    return f"`the smallest majority of {word} nests`"


def wit(word, i):
    return f"`the birds of nest {i} of {word} that Reiss's division puts above`"


# ---------------------------------------------------------------- the module template
m = []
m += ["IMPORT prelude", ""]
m += [
    "-- Mishnah Kinnim: 3:2's \"majority\" AT A FIXED NUMBER OF OWNERS, with no list and no recursion.",
    "-- Generated by tools/gen_fixed_arity.py (then tools/render.py); change the script, not this file.",
    "-- Target compiler: main.",
    "--",
    "-- The text's own cases are fixed in size: 3:2 names five owners (one, two, three, ten and a hundred",
    "-- pairs), and on Bartenura's reading it speaks of two women at a time.  kn-majority.l4 states Koppel's",
    "-- and Reiss's smallest majority for any number of owners, over a list, and a solver takes no lists.",
    "-- Here the same number is written out for two, three and five owners whose counts are anything: the",
    "-- largest minority is the largest sum of some of the owners' pairs that is no more than half of all of",
    "-- them, over every choice of owners; the smallest majority is all the pairs less it.",
    "-- prove/kn-fixed-arity.l4 proves, for every count, that twice it is the fewest valid offerings over",
    "-- every apportionment; kn-tests.l4 asserts that it equals the list form on the sources' cases.",
    "",
    "§ `Kinnim 3:2 at a fixed number of owners`",
    "",
    "{{Q mishnah-kinnim-3 8 13}}",
    "@ref Kinnim 3:2 and its general principle, Koppel and Reiss, for a fixed number of owners (src:mishnah-kinnim-3:8-13)",
    "GIVEN some IS A NUMBER",
    "      all  IS A NUMBER",
    "GIVETH A NUMBER",
    f"{HALF} some all MEANS",
    "    IF (2 TIMES some) AT MOST all THEN some ELSE 0",
    "",
]
for n, word in SIZES:
    names = ps(n)
    m += [f"§§ `{word.capitalize()} owners`", ""]
    m += given(names) + ["GIVETH A NUMBER", f"{total(word)} {' '.join(names)} MEANS", "    " + " PLUS ".join(names), ""]
    terms = [f"{HALF} {ssum(s, names)} ({total(word)} {' '.join(names)})" for s in subsets(n)]
    m += [f"-- Over all {len(terms)} choices of owners but all of them (all of them hold more than half).",
          f"@ref Kinnim 3:2, the general principle, second clause (src:mishnah-kinnim-3:13)"]
    m += given(names) + ["GIVETH A NUMBER", f"{lm(word)} {' '.join(names)} MEANS", "    " + nested_max(terms), ""]
    m += [f"@ref Kinnim 3:2, the general principle, second clause (src:mishnah-kinnim-3:13)"]
    m += given(names) + ["GIVETH A NUMBER", f"{sm(word)} {' '.join(names)} MEANS",
                         f"    ({total(word)} {' '.join(names)}) MINUS ({lm(word)} {' '.join(names)})", ""]

open(f"{enc}/tools/kn-majority-fixed.l4.in", "w", encoding="utf-8").write("\n".join(m).rstrip("\n") + "\n")

# ---------------------------------------------------------------- the obligations
NEST = "`the valid offerings of a nest of pairs with so many of its birds above`"
LEGAL = "`so many of a nest's birds could be above`"
WHOLE = "`a whole number of pairs`"

o = []
o += ["IMPORT prelude", "IMPORT `kn-nouns`", "IMPORT `kn-ch1`", "IMPORT `kn-majority`", "IMPORT `kn-majority-fixed`", ""]
o += [
    "-- Mishnah Kinnim: 3:2 AT A FIXED NUMBER OF OWNERS, FOR EVERY COUNT.  Generated by",
    "-- tools/gen_fixed_arity.py; change the script, not this file.  Run with ./prove.sh, like",
    "-- kn-obligations.l4, and not checked by ../check.sh, for the same reason.",
    "--",
    "-- kn-obligations.l4 proves the worst case for the sources' cases one at a time.  Here the number of",
    "-- owners is fixed (two, three, five) and their pairs are anything, so each #ASSERT is a theorem about",
    "-- every mixture of that size:",
    "--   1. whatever the apportionment of half the birds above, at least twice the smallest majority are",
    "--      valid (kn-majority-fixed.l4);",
    "--   2. Reiss's division (Torah u-Madda Journal 9, 2000, section 6) is an apportionment of half the",
    "--      birds above, and exactly twice the smallest majority are valid in it: so the bound is the least;",
    "--   and, for two owners, 3. Koppel's and Reiss's majority is Bartenura's larger count.",
    "-- Not stated to the solver: that Reiss's division is in whole birds when the counts are whole.  Each of",
    "-- its values is 0, twice an owner's pairs, or twice the last owner's pairs less (all the pairs less twice",
    "-- the chosen owners' pairs), so it is whole by construction; stated as FLOOR w EQUALS w, the solver",
    "-- timed out at 120 s for every size (2026-11-03), so that step rests on this reading.",
    "-- Each owner's valid count is the encoding's per-nest rule, which kn-obligations.l4 section F proves",
    "-- equal to the rule the search uses.  The general theorem, for any number of owners, is not here: it",
    "-- needs induction, which a solver does not do.",
    "",
    "§ `Kinnim: 3:2 at a fixed number of owners`",
    "",
    "GIVEN p IS A NUMBER",
    "GIVETH A BOOLEAN",
    f"{WHOLE} p MEANS ((FLOOR p) EQUALS p) AND (p AT LEAST 1)",
    "",
]
for n, word in SIZES:
    names = ps(n)
    P = [f"P{n}{i}" for i in range(1, n + 1)]
    A = [f"A{n}{i}" for i in range(1, n + 1)]
    o += [f"§§ `{word.capitalize()} owners`", ""]
    # Reiss's division, one rule per owner
    for i in range(1, n + 1):
        branches = []
        for s in subsets(n):
            rest = [j for j in range(1, n + 1) if j not in s]
            last = rest[0]
            cond = (f"((2 TIMES {ssum(s, names)}) AT MOST ({total(word)} {' '.join(names)})) AND "
                    f"({ssum(s, names)} AT LEAST ({lm(word)} {' '.join(names)}))")
            if i in s:
                val = "0"
            elif i == last:
                val = f"(2 TIMES p{i}) MINUS (({total(word)} {' '.join(names)}) MINUS (2 TIMES {ssum(s, names)}))"
            else:
                val = f"2 TIMES p{i}"
            branches.append((cond, val))
        body = "    " + "".join(f"IF {c} THEN {v} ELSE " for c, v in branches) + "0"
        o += [f"-- Reiss's division, nest {i} of {word}: the first choice of owners that makes up the largest minority"
              f" has all its birds below; the first owner not chosen takes what makes half; the rest are all above."]
        o += given(names) + ["GIVETH A NUMBER", f"{wit(word, i)} {' '.join(names)} MEANS", body, ""]
    o += [f"ASSUME {x} IS A NUMBER" for x in P + A] + [""]
    whole = " AND ".join(f"({WHOLE} {x})" for x in P)
    legal = " AND ".join(f"({LEGAL} {p} {a})" for p, a in zip(P, A))
    half = f"(({' PLUS '.join(A)}) EQUALS ({' PLUS '.join(P)}))"
    valid = " PLUS ".join(f"({NEST} {p} {a})" for p, a in zip(P, A))
    smv = f"(2 TIMES ({sm(word)} {' '.join(P)}))"
    o += [f"-- 1. The bound, for every {word} owners and every apportionment of half the birds above."]
    o += [f"#ASSERT ({whole} AND {legal} AND {half}) IMPLIES (({valid}) AT LEAST {smv})", ""]
    W = [f"({wit(word, i)} {' '.join(P)})" for i in range(1, n + 1)]
    some = " AND ".join(f"({x} AT LEAST 1)" for x in P)
    wrange = " AND ".join(f"(({w} AT LEAST 0) AND ({w} AT MOST (2 TIMES {p})))" for p, w in zip(P, W))
    whalf = f"(({' PLUS '.join(W)}) EQUALS ({' PLUS '.join(P)}))"
    wvalid = " PLUS ".join(f"({NEST} {p} {w})" for p, w in zip(P, W))
    o += [f"-- 2. Reiss's division puts between none and all of each owner's birds above, half of all the birds",
          f"-- above in total, and reaches the bound: for every count of at least one pair, whole or not."]
    o += [f"#ASSERT ({some}) IMPLIES ({wrange} AND {whalf} AND (({wvalid}) EQUALS {smv}))", ""]
    if n == 2:
        o += ["-- 3. For two owners, the smallest majority is the larger owner's pairs: Koppel's and Reiss's reading",
              "-- and Bartenura's give the same number (Beller, Higayon 5, p. 156: for two women the two readings coincide)."]
        o += [f"#ASSERT ({whole}) IMPLIES (({sm(word)} {' '.join(P)}) EQUALS (max {P[0]} {P[1]}))", ""]

open(f"{enc}/prove/kn-fixed-arity.l4", "w", encoding="utf-8").write("\n".join(o).rstrip("\n") + "\n")
print("wrote tools/kn-majority-fixed.l4.in and prove/kn-fixed-arity.l4")
